#!/usr/bin/env bash
# Build cesium_rs.wasm and embed it, with the Earth texture, in the Lakebed
# capsule under web/. A capsule can only ship a favicon as a static file, so
# both binaries travel inside the client bundle as base64.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

cargo build --release --target wasm32-unknown-unknown
wasm="target/wasm32-unknown-unknown/release/cesium_rs.wasm"
earth="assets/natural-earth-ii-2048.jpg"
out="web/client/generated"
mkdir -p "$out"

emit() {
  local name="$1" file="$2" dest="$3"
  {
    echo "// Generated by scripts/build-web.sh from $file. Do not edit."
    printf 'export const %s = "' "$name"
    base64 -w0 "$file"
    echo '";'
  } >"$dest"
}

emit WASM_BASE64 "$wasm" "$out/wasm.ts"
emit EARTH_JPEG_BASE64 "$earth" "$out/earth.ts"
echo "wasm $(stat -c%s "$wasm") bytes, earth $(stat -c%s "$earth") bytes"
