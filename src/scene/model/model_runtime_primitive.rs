//! CesiumJS `Scene/Model/ModelRuntimePrimitive`: a runtime mesh primitive.
//!
//! The render lane owns draw-command construction. This module defines the
//! [`RuntimeDrawCommand`] boundary the runtime needs for
//! `ModelMatrixUpdateStage` and the scene graph's render-state traversal, plus
//! the pipeline-stage sequence Cesium configures per frame.

use super::{model_utility, ModelPipelineProperties};
use crate::{
    core::{BoundingSphere, Matrix4, PrimitiveType},
    renderer::{Buffer, Gl},
    scene::{model_components as mc, CullFace, SceneMode},
};

/// The parts of a draw command the model runtime mutates.
///
/// Implement this for the render lane's `ModelDrawCommand` so
/// `ModelMatrixUpdateStage` can update `modelMatrix` and the cull face in
/// place, and so `update_back_face_culling`, `update_shadows` and
/// `update_show_bounding_volume` reach every primitive.
pub trait RuntimeDrawCommand {
    fn model_matrix(&self) -> &Matrix4;
    fn set_model_matrix(&mut self, model_matrix: Matrix4);
    /// The primitive type, used to recompute the cull face after a transform
    /// change. `None` when the draw command has no primitive type.
    fn primitive_type(&self) -> Option<PrimitiveType>;
    fn set_cull_face(&mut self, cull_face: CullFace);
    fn set_back_face_culling(&mut self, back_face_culling: bool);
    fn set_shadows(&mut self, shadows: bool);
    fn set_debug_show_bounding_volume(&mut self, show: bool);
}

static DUMMY_IDENTITY_MATRIX: Matrix4 = Matrix4::IDENTITY;

impl RuntimeDrawCommand for () {
    fn model_matrix(&self) -> &Matrix4 {
        &DUMMY_IDENTITY_MATRIX
    }
    fn set_model_matrix(&mut self, _: Matrix4) {}
    fn primitive_type(&self) -> Option<PrimitiveType> {
        None
    }
    fn set_cull_face(&mut self, _: CullFace) {}
    fn set_back_face_culling(&mut self, _: bool) {}
    fn set_shadows(&mut self, _: bool) {}
    fn set_debug_show_bounding_volume(&mut self, _: bool) {}
}

/// Primitive-level pipeline stages, in the order `configure_pipeline` pushes
/// them. The render lane executes the matching stage.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PrimitivePipelineStage {
    SceneMode2D,
    Geometry,
    Wireframe,
    Classification,
    MorphTargets,
    Skinning,
    PointCloudStyling,
    Dequantization,
    Imagery,
    Material,
    FeatureId,
    Metadata,
    MetadataPicking,
    SelectedFeatureId,
    BatchTexture,
    CpuStyling,
    VerticalExaggeration,
    CustomShader,
    Lighting,
    Picking,
    PrimitiveOutline,
    EdgeVisibility,
    EdgeDetection,
    Alpha,
    PrimitiveStatistics,
}

/// Feature IDs inspected by `configurePipeline`.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct FeatureIdFlags {
    pub has_feature_ids: bool,
    pub has_property_table: bool,
}

/// In-memory representation of a single primitive and its mesh.
///
/// `D` is the render lane's draw-command type, defaulting to `()` so the
/// runtime can be built and validated without a renderer.
pub struct ModelRuntimePrimitive<G: Gl, D = ()> {
    /// Index of the owning node in the scene graph.
    pub node_index: usize,
    /// Index of the primitive in the owning node's `primitives`.
    pub primitive_index: usize,
    /// Pipeline stages to apply to this primitive, in order.
    pub pipeline_stages: Vec<PrimitivePipelineStage>,
    /// The generated draw command, owned by the render lane.
    pub draw_command: Option<D>,
    /// The primitive's bounding sphere in object space.
    pub bounding_sphere: Option<BoundingSphere>,
    /// The primitive's bounding sphere in 2D world space.
    pub bounding_sphere_2d: Option<BoundingSphere>,
    /// Positions projected to 2D world space, generated by
    /// `SceneMode2DPipelineStage`.
    pub position_buffer_2d: Option<Buffer<G>>,
    /// Vertex-batch lengths and offsets generated by
    /// `ClassificationPipelineStage`.
    pub batch_lengths: Option<Vec<usize>>,
    pub batch_offsets: Option<Vec<usize>>,
}

impl<G: Gl, D> ModelRuntimePrimitive<G, D> {
    pub fn new(node_index: usize, primitive_index: usize) -> Self {
        Self {
            node_index,
            primitive_index,
            pipeline_stages: Vec::new(),
            draw_command: None,
            bounding_sphere: None,
            bounding_sphere_2d: None,
            position_buffer_2d: None,
            batch_lengths: None,
            batch_offsets: None,
        }
    }

    /// Configures the primitive's pipeline stages. Call it again if the
    /// pipeline needs to be re-run.
    ///
    /// `request_edge_visibility` mirrors Cesium's side effect on
    /// `frameState.edgeVisibilityRequested`: it becomes `true` when the
    /// primitive has edge visibility and the edge stages are configured.
    #[allow(clippy::too_many_arguments)]
    pub fn configure_pipeline(
        &mut self,
        properties: &ModelPipelineProperties,
        node: &mc::Node<G>,
        primitive: &mc::Primitive<G>,
        mode: SceneMode,
        scene_3d_only: bool,
        vertical_exaggeration: f64,
        request_edge_visibility: &mut bool,
    ) {
        let stages = &mut self.pipeline_stages;
        stages.clear();

        let use_webgl2 = properties.use_webgl2;
        let use_2d = mode != SceneMode::Scene3D && !scene_3d_only && properties.project_to_2d;
        let has_vertical_exaggeration = vertical_exaggeration != 1.0 && properties.has_vertical_exaggeration;

        let has_morph_targets = !primitive.morph_targets.is_empty();
        let has_skinning = node.skin.is_some();
        let has_imagery_layers = properties.has_imagery_layers;

        let has_custom_shader = properties.custom_shader.is_some();
        let materials_enabled = match &properties.custom_shader {
            Some(custom_shader) => !custom_shader.has_fragment_shader || !custom_shader.replace_material,
            None => true,
        };
        let has_quantization = model_utility::has_quantized_attributes(Some(&primitive.attributes));

        let generate_wireframe_indices = properties.debug_wireframe
            && primitive.primitive_type.is_some_and(PrimitiveType::is_triangles)
            // Generating index buffers for wireframes is always possible in
            // WebGL2, but only works in WebGL1 when the model was constructed
            // with `enableDebugWireframe`.
            && (properties.enable_debug_wireframe || use_webgl2);

        let has_attenuation = properties.point_cloud_shading.is_some_and(|p| p.attenuation);
        let has_point_cloud_back_face_culling = properties.point_cloud_shading.is_some_and(|p| p.back_face_culling);
        let has_point_cloud_style = primitive.primitive_type == Some(PrimitiveType::Points)
            && (properties.has_style || has_attenuation || has_point_cloud_back_face_culling);

        let has_outlines = properties.enable_show_outline && primitive.outline_coordinates.is_some();
        let has_edge_visibility = primitive.edge_visibility.is_some();
        let has_classification = properties.classification_type.is_some();

        let feature_id_flags = inspect_feature_ids(properties, node, primitive);

        // Pipeline sequence, matching ModelRuntimePrimitive.configurePipeline.
        if use_2d {
            stages.push(PrimitivePipelineStage::SceneMode2D);
        }
        stages.push(PrimitivePipelineStage::Geometry);
        if generate_wireframe_indices {
            stages.push(PrimitivePipelineStage::Wireframe);
        }
        if has_classification {
            stages.push(PrimitivePipelineStage::Classification);
        }
        if has_morph_targets {
            stages.push(PrimitivePipelineStage::MorphTargets);
        }
        if has_skinning {
            stages.push(PrimitivePipelineStage::Skinning);
        }
        if has_point_cloud_style {
            stages.push(PrimitivePipelineStage::PointCloudStyling);
        }
        if has_quantization {
            stages.push(PrimitivePipelineStage::Dequantization);
        }
        if has_imagery_layers && !has_outlines {
            stages.push(PrimitivePipelineStage::Imagery);
        }
        if materials_enabled {
            stages.push(PrimitivePipelineStage::Material);
        }
        // These stages always run so their structs are declared.
        stages.push(PrimitivePipelineStage::FeatureId);
        stages.push(PrimitivePipelineStage::Metadata);
        stages.push(PrimitivePipelineStage::MetadataPicking);
        if feature_id_flags.has_property_table {
            stages.push(PrimitivePipelineStage::SelectedFeatureId);
            stages.push(PrimitivePipelineStage::BatchTexture);
            stages.push(PrimitivePipelineStage::CpuStyling);
        }
        if has_vertical_exaggeration {
            stages.push(PrimitivePipelineStage::VerticalExaggeration);
        }
        if has_custom_shader {
            stages.push(PrimitivePipelineStage::CustomShader);
        }
        stages.push(PrimitivePipelineStage::Lighting);
        if properties.allow_picking {
            stages.push(PrimitivePipelineStage::Picking);
        }
        if has_outlines {
            stages.push(PrimitivePipelineStage::PrimitiveOutline);
        }
        if has_edge_visibility {
            *request_edge_visibility = true;
            stages.push(PrimitivePipelineStage::EdgeVisibility);
            stages.push(PrimitivePipelineStage::EdgeDetection);
        }
        stages.push(PrimitivePipelineStage::Alpha);
        stages.push(PrimitivePipelineStage::PrimitiveStatistics);
    }
}

/// Checks instances first, as that is the most specific kind of feature ID.
fn inspect_feature_ids<G: Gl>(
    properties: &ModelPipelineProperties,
    node: &mc::Node<G>,
    primitive: &mc::Primitive<G>,
) -> FeatureIdFlags {
    if let Some(instances) = &node.instances {
        if let Some(feature_ids) =
            model_utility::get_feature_ids_by_label(&instances.feature_ids, &properties.instance_feature_id_label)
        {
            return FeatureIdFlags {
                has_feature_ids: true,
                has_property_table: feature_ids.property_table_id().is_some(),
            };
        }
    }
    if let Some(feature_ids) =
        model_utility::get_feature_ids_by_label(&primitive.feature_ids, &properties.feature_id_label)
    {
        return FeatureIdFlags { has_feature_ids: true, has_property_table: feature_ids.property_table_id().is_some() };
    }
    FeatureIdFlags::default()
}

impl<G: Gl, D> std::fmt::Debug for ModelRuntimePrimitive<G, D> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ModelRuntimePrimitive")
            .field("node_index", &self.node_index)
            .field("primitive_index", &self.primitive_index)
            .field("pipeline_stages", &self.pipeline_stages)
            .finish_non_exhaustive()
    }
}
