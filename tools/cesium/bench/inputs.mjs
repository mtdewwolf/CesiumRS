// Writes the generated inputs for the parity benchmark to target/bench-inputs.
//
//   node tools/cesium/bench/inputs.mjs
//
// The fixtures are small by design (heightmaps up to 6x6, a 2-triangle Draco
// mesh), so tile-sized inputs are generated here, deterministically, for both
// sides to read. There is no recorded result for these; compare.mjs checks the
// CesiumRS checksum against the CesiumJS one instead.

import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Cartesian3, Rectangle } from "@cesium/engine";
import { makeRng } from "../fixtures/lib.mjs";

const require = createRequire(import.meta.url);
const draco3d = require("draco3d");

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const outDir = join(root, "target/bench-inputs");

/** A 1-arc-degree-ish mountain tile in the heightmap-1.0 layout CesiumTerrainProvider serves. */
function heightmap(size, seed) {
  const rng = makeRng(seed);
  const span = 0.17578125; // a level-10 geographic tile
  const west = 10.0;
  const south = 46.0;
  const rect = Rectangle.fromDegrees(west, south, west + span, south + span);
  const center = Cartesian3.fromRadians((rect.west + rect.east) / 2, (rect.south + rect.north) / 2, 0);
  const heightScale = 0.2;
  const heightOffset = -1000;
  const data = [];
  for (let row = 0; row < size; row++) {
    for (let col = 0; col < size; col++) {
      const u = col / (size - 1);
      const v = row / (size - 1);
      const meters =
        1800 + 900 * Math.sin(u * 5.1 + 0.3) * Math.cos(v * 4.3) + 350 * Math.sin(u * 17 + v * 11) + 40 * (rng() - 0.5);
      data.push(Math.max(0, Math.min(65535, Math.round((meters - heightOffset) / heightScale))));
    }
  }
  return {
    kind: "heightmap",
    note: `${size}x${size} Uint16 heightmap tile, generated by tools/cesium/bench/inputs.mjs`,
    options: {
      data,
      type: "Uint16Array",
      width: size,
      height: size,
      native: [west, south, west + span, south + span],
      rectangle: [rect.west, rect.south, rect.east, rect.north],
      center: [center.x, center.y, center.z],
      isGeographic: true,
      ellipsoid: "WGS84",
      skirtHeight: 50,
      includeWebMercatorT: true,
      exaggeration: 1,
      exaggerationRelativeHeight: 0,
      structure: { heightScale, heightOffset },
    },
  };
}

function bytesOf(out, length) {
  const raw = new Uint8Array(length);
  for (let i = 0; i < length; i++) raw[i] = out.GetValue(i) & 0xff;
  return raw;
}

/** An n x n vertex terrain-like grid with normals and texture coordinates, Draco-encoded. */
function dracoGrid(encoderModule, n) {
  const count = n * n;
  const positions = new Float32Array(count * 3);
  const normals = new Float32Array(count * 3);
  const uvs = new Float32Array(count * 2);
  const height = (x, y) => 40 * Math.sin(x / 90) * Math.cos(y / 70) + 8 * Math.sin((x + y) / 23);
  const step = 1000 / (n - 1);
  for (let row = 0; row < n; row++) {
    for (let col = 0; col < n; col++) {
      const i = row * n + col;
      const x = col * step;
      const y = row * step;
      positions.set([x, y, height(x, y)], i * 3);
      const dx = (height(x + 1, y) - height(x - 1, y)) / 2;
      const dy = (height(x, y + 1) - height(x, y - 1)) / 2;
      const length = Math.hypot(dx, dy, 1);
      normals.set([-dx / length, -dy / length, 1 / length], i * 3);
      uvs.set([col / (n - 1), row / (n - 1)], i * 2);
    }
  }
  const faces = new Uint32Array((n - 1) * (n - 1) * 6);
  let f = 0;
  for (let row = 0; row < n - 1; row++) {
    for (let col = 0; col < n - 1; col++) {
      const a = row * n + col;
      faces.set([a, a + 1, a + n, a + 1, a + n + 1, a + n], f);
      f += 6;
    }
  }
  const builder = new encoderModule.MeshBuilder();
  const mesh = new encoderModule.Mesh();
  const ids = {
    POSITION: builder.AddFloatAttributeToMesh(mesh, encoderModule.POSITION, count, 3, positions),
    NORMAL: builder.AddFloatAttributeToMesh(mesh, encoderModule.NORMAL, count, 3, normals),
    TEX_COORD: builder.AddFloatAttributeToMesh(mesh, encoderModule.TEX_COORD, count, 2, uvs),
  };
  builder.AddFacesToMesh(mesh, faces.length / 3, faces);
  const encoder = new encoderModule.Encoder();
  encoder.SetAttributeQuantization(encoderModule.POSITION, 14);
  encoder.SetAttributeQuantization(encoderModule.NORMAL, 10);
  encoder.SetAttributeQuantization(encoderModule.TEX_COORD, 12);
  encoder.SetSpeedOptions(5, 5);
  const out = new encoderModule.DracoInt8Array();
  const length = encoder.EncodeMeshToDracoBuffer(mesh, out);
  if (!length) throw new Error("Draco encode failed");
  const raw = bytesOf(out, length);
  for (const object of [out, encoder, mesh, builder]) encoderModule.destroy(object);
  return {
    kind: "draco",
    note: `${n}x${n} vertex grid, ${faces.length / 3} triangles, generated by tools/cesium/bench/inputs.mjs`,
    triangles: faces.length / 3,
    vertices: count,
    byteLength: raw.length,
    compressedAttributes: ids,
    base64: Buffer.from(raw).toString("base64"),
  };
}

const encoderModule = await draco3d.createEncoderModule();
const inputs = {
  "heightmap65.json": heightmap(65, 9001),
  "heightmap257.json": heightmap(257, 9002),
  "draco5k.json": dracoGrid(encoderModule, 51),
  "draco130k.json": dracoGrid(encoderModule, 256),
};
mkdirSync(outDir, { recursive: true });
for (const [name, value] of Object.entries(inputs)) {
  writeFileSync(join(outDir, name), JSON.stringify(value));
  console.error(`wrote target/bench-inputs/${name}${value.byteLength ? ` (${value.byteLength} Draco bytes)` : ""}`);
}
