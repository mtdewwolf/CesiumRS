// Writes PORTING.md: every module in @cesium/engine 23.0.0 (CesiumJS 1.139),
// its line count, and its port status from status.json.
//
//   npm run tracker
//
// status.json maps "Package/Module" to { status, rust?, note? }, where status
// is "ported", "partial", or "n/a". Modules not listed are not started.
// Progress is weighted by JavaScript lines and excludes "n/a" modules.
//
// Also draws docs/progress.svg (per package) and docs/progress-history.svg
// (overall percentage per milestone, kept in history.json). Pass
// `--milestone "name"` to start a new milestone; otherwise the last one is
// updated in place.
//
// The Plan section of PORTING.md comes from plan.md, which is edited by hand.

import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "node_modules/@cesium/engine/Source");
const packages = ["Core", "Scene", "DataSources", "Renderer", "Workers", "Shaders"];
const status = JSON.parse(readFileSync(join(here, "status.json"), "utf8"));

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out.push(...walk(path));
    else if (name.endsWith(".js")) out.push(path);
  }
  return out;
}

const rows = [];
for (const pkg of packages) {
  for (const file of walk(join(source, pkg))) {
    const id = relative(source, file).replace(/\.js$/, "");
    const lines = readFileSync(file, "utf8").split("\n").length;
    rows.push({ pkg, id, lines, ...(status[id] ?? { status: "todo" }) });
  }
}

const unknown = Object.keys(status).filter((id) => !rows.some((r) => r.id === id));
if (unknown.length) throw new Error(`status.json names modules that do not exist: ${unknown.join(", ")}`);

const weight = { ported: 1, partial: 0.5, todo: 0 };
function summary(list) {
  const counted = list.filter((r) => r.status !== "n/a");
  const total = counted.reduce((s, r) => s + r.lines, 0);
  const done = counted.reduce((s, r) => s + r.lines * weight[r.status], 0);
  const count = (s) => list.filter((r) => r.status === s).length;
  return {
    modules: list.length,
    ported: count("ported"),
    partial: count("partial"),
    na: count("n/a"),
    todo: count("todo"),
    lines: total,
    percent: total ? (100 * done) / total : 0,
  };
}

const icon = { ported: "✅ ported", partial: "🟡 partial", "n/a": "➖ n/a", todo: "⬜ todo" };
const all = summary(rows);
let md = `# Port tracker

Generated by \`tools/cesium/tracker.mjs\` from \`@cesium/engine\` 23.0.0 (CesiumJS 1.139) and \`tools/cesium/status.json\`. Do not edit by hand.

![Progress by package](docs/progress.svg)

![Overall progress over time](docs/progress-history.svg)

**Overall: ${all.percent.toFixed(1)}%** of ${all.lines.toLocaleString("en-US")} applicable JavaScript lines. Progress is weighted by line count (partial = half) and leaves out modules marked n/a.

- ✅ **ported**: the module's public behaviour exists in Rust and is checked against CesiumJS fixtures (\`tests/fixtures\`) or ported unit tests.
- 🟡 **partial**: some of the module is ported; the note says what is missing.
- ➖ **n/a**: a JavaScript or browser idiom with no Rust counterpart; the note says what replaces it.
- ⬜ **todo**: not started.

| Package | Modules | Ported | Partial | Todo | n/a | Progress |
| --- | ---: | ---: | ---: | ---: | ---: | ---: |
`;
for (const pkg of packages) {
  const s = summary(rows.filter((r) => r.pkg === pkg));
  md += `| ${pkg} | ${s.modules} | ${s.ported} | ${s.partial} | ${s.todo} | ${s.na} | ${s.percent.toFixed(1)}% |\n`;
}
md += `| **Total** | ${all.modules} | ${all.ported} | ${all.partial} | ${all.todo} | ${all.na} | **${all.percent.toFixed(1)}%** |\n`;

// The hand-written plan (plan.md), headed by the live distance to the Core milestone.
{
  const core = summary(rows.filter((r) => r.pkg === "Core"));
  const target = 100;
  const remaining = Math.max(0, Math.ceil(((target - core.percent) / 100) * core.lines));
  md += `\n## Plan\n\n**Core: ${core.percent.toFixed(1)}%** of ${core.lines.toLocaleString("en-US")} lines. `;
  md += remaining > 0
    ? `The ${target}% Core milestone needs about ${remaining.toLocaleString("en-US")} more ported lines.\n`
    : `The ${target}% Core milestone is reached.\n`;
  const plan = join(here, "plan.md");
  if (existsSync(plan)) md += `\n${readFileSync(plan, "utf8").trim()}\n`;
}

for (const pkg of packages) {
  md += `\n## ${pkg}\n\n| Module | Lines | Status | Rust | Note |\n| --- | ---: | --- | --- | --- |\n`;
  for (const r of rows.filter((x) => x.pkg === pkg)) {
    const name = r.id.slice(pkg.length + 1);
    md += `| ${name} | ${r.lines} | ${icon[r.status]} | ${r.rust ? `\`${r.rust}\`` : ""} | ${r.note ?? ""} |\n`;
  }
}

writeFileSync(join(here, "../../PORTING.md"), md);

// Keep README metrics derived from the same status rows as PORTING.md.
// The capability descriptions and roadmap remain hand-written.
{
  const readmeFile = join(here, "../../README.md");
  const readme = readFileSync(readmeFile, "utf8");
  const core = summary(rows.filter((r) => r.pkg === "Core"));
  const remaining = Math.max(0, Math.ceil(((100 - core.percent) / 100) * core.lines));
  const count = (n) => n.toLocaleString("en-US");
  const status = `**Status: ${all.percent.toFixed(1)}% of CesiumJS ported** (${count(all.ported)} fully ported and ${count(all.partial)} partial of ${count(all.modules - all.na)} applicable modules, weighted by JavaScript lines). **Core, the math, geometry and time foundation, is at ${core.percent.toFixed(1)}%, working toward 100% Core** (${count(remaining)} more lines). [PORTING.md](PORTING.md) lists every module with its status, and its [Plan](PORTING.md#plan) section lists the roadmap to 100% Core.`;
  function fixtureCount(dir) {
    let total = 0;
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) total += fixtureCount(path);
      else if (entry.name.endsWith(".json")) {
        const fixture = JSON.parse(readFileSync(path, "utf8"));
        if (!Array.isArray(fixture.cases)) throw new Error(`Missing cases in fixture: ${path}`);
        total += fixture.cases.length;
      }
    }
    return total;
  }
  const statusPattern = /^\*\*Status: .*$/m;
  const casesPattern = /\*\*[\d,]+ cases\*\*/;
  if (!statusPattern.test(readme) || !casesPattern.test(readme)) {
    throw new Error("README.md is missing its progress paragraph or fixture count");
  }
  const cases = fixtureCount(join(here, "../../tests/fixtures"));
  writeFileSync(readmeFile, readme.replace(statusPattern, status).replace(casesPattern, `**${count(cases)} cases**`));
}

// ---- Charts ----

const esc = (t) => String(t).replace(/&/g, "&amp;").replace(/</g, "&lt;");
const style = `<style>text{font:13px system-ui,-apple-system,Segoe UI,sans-serif;fill:#1f2328}.dim{fill:#59636e}.bg{fill:#eaeef2}.done{fill:#1a7f37}.part{fill:#d4a72c}@media (prefers-color-scheme:dark){text{fill:#e6edf3}.dim{fill:#9198a1}.bg{fill:#30363d}.done{fill:#3fb950}}</style>`;
const docs = join(here, "../../docs");
mkdirSync(docs, { recursive: true });

{
  const bars = [...packages.map((p) => [p, rows.filter((r) => r.pkg === p)]), ["Total", rows]];
  const W = 640, left = 110, barW = 400, rowH = 30, top = 34;
  const H = top + bars.length * rowH + 10;
  let svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">${style}`;
  svg += `<text x="0" y="18" font-weight="600">CesiumRS port progress (weighted by JavaScript lines)</text>`;
  bars.forEach(([name, list], i) => {
    const s = summary(list);
    const counted = list.filter((r) => r.status !== "n/a");
    const ported = counted.filter((r) => r.status === "ported").reduce((a, r) => a + r.lines, 0) / (s.lines || 1);
    const partial = counted.filter((r) => r.status === "partial").reduce((a, r) => a + r.lines, 0) / (s.lines || 1);
    const y = top + i * rowH;
    const bold = name === "Total" ? ' font-weight="600"' : "";
    svg += `<text x="0" y="${y + 15}"${bold}>${esc(name)}</text>`;
    svg += `<rect class="bg" x="${left}" y="${y + 3}" width="${barW}" height="16" rx="3"/>`;
    svg += `<rect class="done" x="${left}" y="${y + 3}" width="${(barW * ported).toFixed(1)}" height="16" rx="3"/>`;
    if (partial > 0) svg += `<rect class="part" x="${(left + barW * ported).toFixed(1)}" y="${y + 3}" width="${Math.max(1, barW * partial).toFixed(1)}" height="16"/>`;
    svg += `<text x="${left + barW + 10}" y="${y + 15}"${bold}>${s.percent.toFixed(1)}%</text>`;
    svg += `<text class="dim" x="${left + barW + 62}" y="${y + 15}">${s.ported}/${s.modules - s.na}</text>`;
  });
  writeFileSync(join(docs, "progress.svg"), svg + "</svg>\n");
}

{
  const historyFile = join(here, "history.json");
  const history = existsSync(historyFile) ? JSON.parse(readFileSync(historyFile, "utf8")) : [];
  const flag = process.argv.indexOf("--milestone");
  const entry = { milestone: flag > 0 ? process.argv[flag + 1] : history.at(-1)?.milestone ?? "Start", date: new Date().toISOString().slice(0, 10), percent: Number(all.percent.toFixed(2)), ported: all.ported };
  if (flag > 0 || !history.length) history.push(entry);
  else history[history.length - 1] = entry;
  writeFileSync(historyFile, JSON.stringify(history, null, 2) + "\n");

  const W = 720, H = 320, l = 90, r = 70, t = 44, b = 124;
  const max = Math.max(10, Math.ceil(Math.max(...history.map((h) => h.percent)) / 10) * 10);
  const x = (i) => l + (history.length === 1 ? (W - l - r) / 2 : (i * (W - l - r)) / (history.length - 1));
  const y = (p) => t + (H - t - b) * (1 - p / max);
  let svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">${style}`;
  svg += `<text x="0" y="18" font-weight="600">Overall progress over time</text>`;
  for (let p = 0; p <= max; p += max / 5) {
    svg += `<rect class="bg" x="${l}" y="${y(p).toFixed(1)}" width="${W - l - r}" height="1"/>`;
    svg += `<text class="dim" x="${l - 40}" y="${(y(p) + 4).toFixed(1)}" text-anchor="end">${p}%</text>`;
  }
  const pts = history.map((h, i) => `${x(i).toFixed(1)},${y(h.percent).toFixed(1)}`).join(" ");
  svg += `<polyline points="${pts}" fill="none" stroke="#1a7f37" stroke-width="2.5"/>`;
  history.forEach((h, i) => {
    svg += `<circle class="done" cx="${x(i).toFixed(1)}" cy="${y(h.percent).toFixed(1)}" r="4"/>`;
    // Angled so long milestone names do not overlap.
    const ly = H - b + 16;
    svg += `<text class="dim" x="${x(i).toFixed(1)}" y="${ly}" text-anchor="end" transform="rotate(-35 ${x(i).toFixed(1)} ${ly})">${esc(h.milestone)}</text>`;
    svg += `<text x="${x(i).toFixed(1)}" y="${(y(h.percent) - 9).toFixed(1)}" text-anchor="middle">${h.percent.toFixed(1)}%</text>`;
  });
  writeFileSync(join(docs, "progress-history.svg"), svg + "</svg>\n");
}
console.log(`PORTING.md: ${all.percent.toFixed(2)}% (${all.ported} ported, ${all.partial} partial, ${all.todo} todo, ${all.na} n/a)`);
